#!/usr/bin/env node
// Sync the vendored Databricks metric view engine (built in the sigma-data-model-mcp repo)
// into this single-file app.
//
//   node scripts/sync-dbx-metric-view.mjs <path-to-mcp-repo>          # write
//   node scripts/sync-dbx-metric-view.mjs <path-to-mcp-repo> --check  # exit 1 if stale
//
// Reads <mcp>/vendor/dbx-metric-view/{dbx-metric-view-embed.iife.min.js,PROVENANCE.json} (plus LICENSE / NOTICE
// when the MCP repo ships them), verifies the IIFE sha256 against PROVENANCE.json (`sha256[<iife name>]`), copies
// PROVENANCE.json (and LICENSE / NOTICE when present) to ./vendor/dbx-metric-view/, and replaces the generated
// block in index.html. Idempotent. The block sits right after the semantic-tools block (inserted there on the first run).
import { readFileSync, writeFileSync, mkdirSync, existsSync, unlinkSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const BEGIN = '<!-- BEGIN dbx-metric-view (generated by scripts/sync-dbx-metric-view.mjs — do not edit) -->';
const END = '<!-- END dbx-metric-view -->';
// First run: the block is inserted right after the semantic-tools block (before the main app <script>, so DbxMetricView is defined first).
const ANCHOR = '<!-- END semantic-tools -->';

const args = process.argv.slice(2);
const check = args.includes('--check');
const mcp = args.find(a => !a.startsWith('--'));
if (!mcp) { console.error('usage: sync-dbx-metric-view.mjs <path-to-mcp-repo> [--check]'); process.exit(2); }

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(resolve(mcp), 'vendor', 'dbx-metric-view');
const read = (f) => readFileSync(join(src, f));
const iifeName = 'dbx-metric-view-embed.iife.min.js';

const iifeBuf = read(iifeName);
const prov = JSON.parse(read('PROVENANCE.json').toString('utf8'));
const sha = createHash('sha256').update(iifeBuf).digest('hex');
if (prov.sha256?.[iifeName] !== sha) {
  console.error(`sha256 mismatch for ${iifeName}: file=${sha} PROVENANCE=${prov.sha256?.[iifeName]}`);
  process.exit(1);
}
const iife = iifeBuf.toString('utf8');
if (/<\/script/i.test(iife) || iife.includes('<!--')) {
  console.error('IIFE contains </script or <!-- — cannot be inlined safely');
  process.exit(1);
}
const header = `/* dbx-metric-view ${prov.mcpCommit} engine ${prov.engineVersion} — see vendor/dbx-metric-view/ */`;
const block = `${BEGIN}\n<script>${header}\n${iife.replace(/\n+$/, '')}\n</script>\n${END}`;

const indexPath = join(root, 'index.html');
const html = readFileSync(indexPath, 'utf8');
const b = html.indexOf(BEGIN);
const e = html.indexOf(END);
let next;
if (b >= 0 && e > b) {
  next = html.slice(0, b) + block + html.slice(e + END.length);
} else {
  const at = html.indexOf(ANCHOR);
  if (at < 0) { console.error('anchor (semantic-tools END marker) for first-run insertion not found — run scripts/sync-semantic-tools.mjs first'); process.exit(1); }
  const after = at + ANCHOR.length;
  next = html.slice(0, after) + '\n' + block + html.slice(after);
}

// PROVENANCE.json is required; LICENSE / NOTICE are copied when the MCP repo has them (and removed here when it does not).
const dst = join(root, 'vendor', 'dbx-metric-view');
const vendorFiles = [['PROVENANCE.json', read('PROVENANCE.json')]];
const optional = [];
for (const f of ['LICENSE', 'NOTICE']) {
  if (existsSync(join(src, f))) vendorFiles.push([f, read(f)]);
  else optional.push(f);
}

if (check) {
  let stale = next !== html;
  for (const [f, buf] of vendorFiles) {
    const p = join(dst, f);
    if (!existsSync(p) || !readFileSync(p).equals(buf)) { console.error(`stale: vendor/dbx-metric-view/${f}`); stale = true; }
  }
  for (const f of optional) if (existsSync(join(dst, f))) { console.error(`stale: vendor/dbx-metric-view/${f} (no longer in the MCP repo)`); stale = true; }
  if (stale) { console.error('dbx-metric-view is out of sync — run scripts/sync-dbx-metric-view.mjs'); process.exit(1); }
  console.log(`dbx-metric-view in sync (${String(prov.mcpCommit).slice(0, 7)} engine ${prov.engineVersion})`);
  console.log(`MCP PROVENANCE sourceSha256: ${prov.sourceSha256 ?? '(not present in PROVENANCE.json)'}`);
  process.exit(0);
}

mkdirSync(dst, { recursive: true });
for (const [f, buf] of vendorFiles) writeFileSync(join(dst, f), buf);
for (const f of optional) if (existsSync(join(dst, f))) unlinkSync(join(dst, f));
if (next !== html) writeFileSync(indexPath, next);
console.log(`${next !== html ? 'updated' : 'unchanged'} index.html (${String(prov.mcpCommit).slice(0, 7)} engine ${prov.engineVersion}, sha256 ${sha.slice(0, 12)})`);
console.log(`MCP PROVENANCE sourceSha256: ${prov.sourceSha256 ?? '(not present in PROVENANCE.json)'}`);

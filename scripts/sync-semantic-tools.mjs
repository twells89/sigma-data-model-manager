#!/usr/bin/env node
// Sync the vendored semantic-tools engine (built in the sigma-data-model-mcp repo)
// into this single-file app.
//
//   node scripts/sync-semantic-tools.mjs <path-to-mcp-repo>          # write
//   node scripts/sync-semantic-tools.mjs <path-to-mcp-repo> --check  # exit 1 if stale
//
// Reads <mcp>/vendor/semantic-tools/{semantic-tools-embed.iife.min.js,PROVENANCE.json,LICENSE,NOTICE},
// verifies the IIFE sha256 against PROVENANCE.json, copies PROVENANCE/LICENSE/NOTICE to
// ./vendor/semantic-tools/, and replaces the generated block in index.html. Idempotent.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const BEGIN = '<!-- BEGIN semantic-tools (generated by scripts/sync-semantic-tools.mjs — do not edit) -->';
const END = '<!-- END semantic-tools -->';
// First run: markers are inserted just before the main app <script> (SemanticTools must be defined before it runs).
const ANCHOR = '<script>\n        // ── API helper ';

const args = process.argv.slice(2);
const check = args.includes('--check');
const mcp = args.find(a => !a.startsWith('--'));
if (!mcp) { console.error('usage: sync-semantic-tools.mjs <path-to-mcp-repo> [--check]'); process.exit(2); }

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(resolve(mcp), 'vendor', 'semantic-tools');
const read = (f) => readFileSync(join(src, f));
const iifeName = 'semantic-tools-embed.iife.min.js';

const iifeBuf = read(iifeName);
const prov = JSON.parse(read('PROVENANCE.json').toString('utf8'));
const sha = createHash('sha256').update(iifeBuf).digest('hex');
if (prov.sha256?.[iifeName] !== sha) {
  console.error(`sha256 mismatch for ${iifeName}: file=${sha} PROVENANCE=${prov.sha256?.[iifeName]}`);
  process.exit(1);
}
const iife = iifeBuf.toString('utf8');
if (/<\/script/i.test(iife) || iife.includes('<!--')) {
  console.error('IIFE contains </script or <!-- — cannot be inlined safely');
  process.exit(1);
}
const header = `/* semantic-tools ${prov.semanticToolsCommit} embed ${prov.embedVersion} — Apache-2.0, see vendor/semantic-tools/ */`;
const block = `${BEGIN}\n<script>${header}\n${iife.replace(/\n+$/, '')}\n</script>\n${END}`;

const indexPath = join(root, 'index.html');
const html = readFileSync(indexPath, 'utf8');
const b = html.indexOf(BEGIN);
const e = html.indexOf(END);
let next;
if (b >= 0 && e > b) {
  next = html.slice(0, b) + block + html.slice(e + END.length);
} else {
  const at = html.indexOf(ANCHOR);
  if (at < 0) { console.error('anchor for first-run marker insertion not found'); process.exit(1); }
  next = html.slice(0, at) + block + '\n    ' + html.slice(at);
}

const vendorFiles = ['PROVENANCE.json', 'LICENSE', 'NOTICE'].map(f => [f, read(f)]);
const dst = join(root, 'vendor', 'semantic-tools');

if (check) {
  let stale = next !== html;
  for (const [f, buf] of vendorFiles) {
    const p = join(dst, f);
    if (!existsSync(p) || !readFileSync(p).equals(buf)) { console.error(`stale: vendor/semantic-tools/${f}`); stale = true; }
  }
  if (stale) { console.error('semantic-tools is out of sync — run scripts/sync-semantic-tools.mjs'); process.exit(1); }
  console.log(`semantic-tools in sync (${prov.semanticToolsCommit.slice(0, 7)} embed ${prov.embedVersion})`);
  console.log(`MCP PROVENANCE sourceSha256: ${prov.sourceSha256 ?? '(missing — rebuild the MCP bundle)'}`);
  process.exit(0);
}

mkdirSync(dst, { recursive: true });
for (const [f, buf] of vendorFiles) writeFileSync(join(dst, f), buf);
if (next !== html) writeFileSync(indexPath, next);
console.log(`${next !== html ? 'updated' : 'unchanged'} index.html (${prov.semanticToolsCommit.slice(0, 7)} embed ${prov.embedVersion}, sha256 ${sha.slice(0, 12)})`);
console.log(`MCP PROVENANCE sourceSha256: ${prov.sourceSha256 ?? '(missing — rebuild the MCP bundle)'}`);
